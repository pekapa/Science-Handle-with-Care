"""Check mod Lua documentation: python3 scripts/lua_docs.py.

Every top-level function needs a LuaLS `---` comment; LuaLS does not flag missing
docs on module-table functions. LuaLS then validates annotations against the
Factorio API definitions generated by the Factorio Modding Tool Kit.
"""

import re
import shutil
import subprocess
import sys

from package import MOD, ROOT

FMTK = "factoriomod-debug@2.1.9"
LIBRARY = ROOT / "build/luals"
FUNCTION = re.compile(r"^(local\s+)?function\s+([\w.:]+)")


def undocumented():
    for path in sorted(MOD.rglob("*.lua")):
        previous = ""
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = FUNCTION.match(line)
            if match and not previous.startswith("---"):
                yield f"{path.relative_to(ROOT)}:{number}: {match[2]} needs a --- doc comment"
            previous = line


def require(tool, hint):
    if not shutil.which(tool):
        sys.exit(f"{tool} not found; {hint}")


def main():
    missing = list(undocumented())
    if missing:
        sys.exit("\n".join(missing))
    require("lua-language-server", "install LuaLS to validate annotations")
    if not (LIBRARY / "factorio/library").is_dir():
        require("npx", "install Node.js to generate the Factorio API definitions")
        subprocess.run(
            ["npx", "--yes", FMTK, "luals-addon", "--online", "latest", str(LIBRARY)],
            check=True,
        )
    result = subprocess.run(
        [
            "lua-language-server",
            "--check",
            str(ROOT),
            "--configpath",
            str(ROOT / ".luarc.json"),
            "--checklevel=Information",
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode:
        problems = [line for line in result.stdout.splitlines() if re.match(r"^\S+\.lua:\d+", line)]
        sys.exit("\n".join(problems) or result.stdout + result.stderr)


if __name__ == "__main__":
    main()
