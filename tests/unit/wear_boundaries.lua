package.path = "./?.lua;" .. package.path
local wear = require("shared.wear")
local function rejects(call)
  assert(not pcall(call), "invalid input was accepted")
end
assert(not wear.is_failed(9) and wear.is_failed(10))
assert(wear.after_pickup(8, 1) == 9)
assert(wear.after_pickup(9, 1) == 10)
assert(wear.after_pickup(8, 2) == 10)
assert(wear.after_pickup(9, 4) == 10)
assert(wear.after_pickup(10, 1) == 10)
assert(wear.after_pickup(100, 1) == 10)
for value = 0, 9 do
  local health = wear.to_health(value)
  assert(math.abs(health - (10 - value) / 10) < 0.0000001)
  assert(wear.from_health(health) == value)
  -- Item health is stored by the engine with floating-point rounding.
  if value > 0 then
    assert(wear.from_health(health + 0.00000003) == value)
    assert(wear.from_health(health - 0.00000003) == value)
  end
end
rejects(function()
  wear.to_health(10)
end)
rejects(function()
  wear.to_health(100)
end)
rejects(function()
  wear.to_health(-1)
end)
rejects(function()
  wear.to_health(0.5)
end)
rejects(function()
  wear.after_pickup(0, 0)
end)
rejects(function()
  wear.from_health(0)
end)
rejects(function()
  wear.from_health(0.99)
end)
rejects(function()
  wear.from_health(0.05)
end)
rejects(function()
  wear.from_health(0.9001)
end)
rejects(function()
  wear.from_health(1.01)
end)
print("wear boundaries passed")
