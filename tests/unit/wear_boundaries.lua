package.path = "./?.lua;" .. package.path
local wear = require("shared.wear")
local function rejects(call)
  assert(not pcall(call), "invalid input was accepted")
end
assert(not wear.is_failed(10) and wear.is_failed(11))
assert(wear.after_pickup(8, 2) == 10)
assert(wear.after_pickup(10, 1) == 11)
assert(wear.after_pickup(9, 4) == 11)
assert(wear.after_pickup(11, 1) == 11)
for value = 0, 11 do
  assert(wear.from_health(wear.to_health(value)) == value)
  assert(wear.to_health(value) > 0)
end
assert(wear.to_health(100) == wear.to_health(11))
rejects(function()
  wear.to_health(-1)
end)
rejects(function()
  wear.to_health(0.5)
end)
rejects(function()
  wear.after_pickup(0, 0)
end)
rejects(function()
  wear.from_health(0)
end)
rejects(function()
  wear.from_health(0.99)
end)
print("wear boundaries passed")
